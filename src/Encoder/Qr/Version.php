    public static function size(int $version): int
    {
        return 17 + $version * 4;
    }

    public static function totalCodewords(int $version): int
    {
        $size = self::size($version);
        $totalModules = $size * $size;

        $funcModules = 64 + 2 * (($size - 16) + ($size - 16)) + 1 + 31;
        if ($version >= 2) {
            $numAlign = count(self::ALIGNMENT_PATTERNS[$version - 2]);
            $funcModules += $numAlign * $numAlign * 25 - (2 * $numAlign - 1) * 5 * 2;
            if ($numAlign > 2) {
                $funcModules -= ($numAlign - 2) * ($numAlign - 2) * 25
                    - (max(0, $numAlign - 3)) * 5;
            }
        }
        if ($version >= 7) {
            $funcModules += 36;
        }

        $dataModules = $totalModules - $funcModules;
        return (int) floor($dataModules / 8);
    }
